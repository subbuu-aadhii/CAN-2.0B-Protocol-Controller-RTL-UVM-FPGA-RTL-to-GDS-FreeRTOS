axs[0].set_title("ASIC sky130 @ 50 MHz: 9.94 mW\n(internal 61 % / switching 39 %)")
axs[1].pie(fpga_pow.values(), labels=[f"{k}\n{v} mW" for k, v in fpga_pow.items()], colors=["#8172B2", "#55A868"],
           startangle=90, wedgeprops=dict(width=0.45))
axs[1].set_title("FPGA Artix-7 demo @ 100 MHz: 82 mW\n(Tj = 25.4 °C)")
labels = ["FPGA demo\n@100 MHz", "FPGA IP OOC\n@200 MHz", "ASIC setup\n@50 MHz", "ASIC hold"]
slack = [0.255, -3.397, 8.38, 0.31]
axs[2].bar(labels, slack, color=["#55A868" if s >= 0 else "#C44E52" for s in slack])
axs[2].axhline(0, color="k", lw=0.8)
