axs[2].set_title("Worst slack (STA)\nOOC @200 MHz used to find Fmax ≈ 119 MHz"); axs[2].set_ylabel("ns")
plt.tight_layout(); plt.savefig(os.path.join(IMG, "val_power_timing.png"), dpi=130); plt.close()
md.append(table([
    ["FPGA IP (OOC)", "1131 LUT, 492 FF, 0 BRAM", "Fmax ≈ 1/(5 ns + 3.397 ns) = 119 MHz", "—"],
    ["FPGA demo (2 nodes)", "1189 LUT, 656 FF (5.7 %)", "WNS +0.255 ns @ 100 MHz, WHS +0.086 ns", "82 mW (72 static)"],
    ["ASIC sky130 hd", "4427 cells, 889 FF, 50 941 µm² cells, die 0.158 mm²", "setup slack +8.38 ns, hold +0.31 ns @ 50 MHz", "9.94 mW typ."],
], ["implementation", "area", "timing", "power"]))

open(os.path.join(ROOT, "00_docs", "validation_results.md"), "w").write("\n".join(md))
json.dump(results, open(os.path.join(ROOT, "00_docs", "validation_results.json"), "w"), indent=1, default=str)
